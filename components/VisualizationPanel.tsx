import React, { useState } from 'react';
import { TripPlan } from '../types';
import { TripTimeline } from './TripTimeline';
import { Map, Calendar, DollarSign, Download, Share2, FileText, Loader2, Check } from 'lucide-react';

interface VisualizationPanelProps {
  plan: TripPlan | null;
  isLoading: boolean;
}

export const VisualizationPanel: React.FC<VisualizationPanelProps> = ({ plan, isLoading }) => {
  const [activeTab, setActiveTab] = useState<'timeline' | 'map' | 'budget'>('timeline');
  const [isExportingDoc, setIsExportingDoc] = useState(false);
  const [docSuccess, setDocSuccess] = useState(false);

  if (!plan && isLoading) {
    return (
      <div className="h-full flex flex-col items-center justify-center text-slate-400">
        <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-brand-500 mb-4"></div>
        <p>Generating your dream trip...</p>
      </div>
    );
  }

  if (!plan) {
    return (
      <div className="h-full flex flex-col items-center justify-center text-slate-400 bg-slate-50/50">
        <Map size={64} className="mb-4 text-slate-300" />
        <p className="font-medium">No trip planned yet</p>
        <p className="text-sm">Chat with the agent to start planning.</p>
      </div>
    );
  }

  const handleExportJson = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(plan, null, 2));
    const downloadAnchorNode = document.createElement('a');
    downloadAnchorNode.setAttribute("href", dataStr);
    downloadAnchorNode.setAttribute("download", "trip_plan.json");
    document.body.appendChild(downloadAnchorNode);
    downloadAnchorNode.click();
    downloadAnchorNode.remove();
  };

  const handleExportDoc = async () => {
    setIsExportingDoc(true);
    
    // Simulate Agent/Backend processing time
    await new Promise(resolve => setTimeout(resolve, 1500));

    // Generate a simple HTML document to represent the Google Doc
    const docContent = `
      <!DOCTYPE html>
      <html>
      <head>
        <title>Trip to ${plan.destination}</title>
        <style>
          body { font-family: 'Arial', sans-serif; max-width: 800px; margin: 40px auto; padding: 20px; line-height: 1.6; color: #333; }
          h1 { color: #2563eb; border-bottom: 2px solid #e2e8f0; padding-bottom: 16px; }
          h2 { color: #1e293b; margin-top: 32px; font-size: 20px; }
          .meta { background: #f8fafc; padding: 16px; border-radius: 8px; border: 1px solid #e2e8f0; margin-bottom: 32px; }
          .activity { margin-bottom: 24px; padding-left: 20px; border-left: 3px solid #cbd5e1; }
          .activity-header { display: flex; justify-content: space-between; font-weight: bold; margin-bottom: 4px; }
          .time { color: #64748b; min-width: 80px; }
          .title { color: #0f172a; }
          .cost { color: #059669; }
          .desc { color: #475569; font-size: 14px; }
          .location { font-style: italic; color: #64748b; font-size: 13px; margin-top: 4px; }
        </style>
      </head>
      <body>
        <h1>Trip Plan: ${plan.destination}</h1>
        
        <div class="meta">
          <strong>Dates:</strong> ${plan.startDate} - ${plan.endDate}<br>
          <strong>Budget:</strong> ${plan.currency} ${plan.totalBudget}
        </div>

        ${plan.itinerary.map(day => `
          <h2>Day ${day.day} - ${day.date}</h2>
          ${day.activities.map(act => `
            <div class="activity">
              <div class="activity-header">
                <div>
                  <span class="time">${act.time}</span>
                  <span class="title">${act.title}</span>
                </div>
                ${act.cost ? `<span class="cost">${plan.currency} ${act.cost}</span>` : ''}
              </div>
              <div class="desc">${act.description}</div>
              ${act.location ? `<div class="location">📍 ${act.location}</div>` : ''}
            </div>
          `).join('')}
        `).join('')}
        
        <div style="margin-top: 50px; font-size: 12px; color: #94a3b8; text-align: center;">
          Generated by WanderAI
        </div>
      </body>
      </html>
    `;

    const blob = new Blob([docContent], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Trip_Plan_${plan.destination.replace(/[^a-z0-9]/gi, '_').toLowerCase()}.html`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    setIsExportingDoc(false);
    setDocSuccess(true);
    setTimeout(() => setDocSuccess(false), 3000);
  };

  return (
    <div className="h-full flex flex-col bg-white">
      {/* Header */}
      <div className="flex items-center justify-between p-6 border-b border-slate-100 bg-white">
        <div>
          <h2 className="text-2xl font-bold text-slate-900">{plan.destination}</h2>
          <div className="text-sm text-slate-500 flex gap-2 items-center mt-1">
            <span>{plan.startDate} - {plan.endDate}</span>
            <span className="w-1 h-1 rounded-full bg-slate-300"></span>
            <span>Budget: {plan.currency} {plan.totalBudget}</span>
          </div>
        </div>
        <div className="flex gap-2">
          {/* Google Doc Export */}
          <button 
            onClick={handleExportDoc}
            disabled={isExportingDoc}
            className={`
              flex items-center gap-2 px-3 py-2 rounded-lg transition-all border
              ${docSuccess 
                ? 'bg-green-50 text-green-600 border-green-200' 
                : 'text-slate-600 border-transparent hover:text-blue-600 hover:bg-blue-50'}
            `}
            title="Export to Google Docs">
            {isExportingDoc ? (
              <Loader2 size={20} className="animate-spin text-blue-500" />
            ) : docSuccess ? (
              <Check size={20} />
            ) : (
              <FileText size={20} />
            )}
            <span className="hidden xl:inline text-sm font-medium">
              {docSuccess ? 'Exported!' : 'Google Doc'}
            </span>
          </button>

          {/* JSON Export */}
          <button 
            onClick={handleExportJson}
            className="p-2 text-slate-600 hover:text-brand-600 hover:bg-brand-50 rounded-lg transition-colors" 
            title="Export JSON">
            <Download size={20} />
          </button>
          
          <button className="p-2 text-slate-600 hover:text-brand-600 hover:bg-brand-50 rounded-lg transition-colors">
            <Share2 size={20} />
          </button>
        </div>
      </div>

      {/* Tabs */}
      <div className="flex px-6 border-b border-slate-100 bg-slate-50/50">
        <button
          onClick={() => setActiveTab('timeline')}
          className={`flex items-center gap-2 py-3 px-4 text-sm font-medium border-b-2 transition-colors ${
            activeTab === 'timeline' 
              ? 'border-brand-500 text-brand-600' 
              : 'border-transparent text-slate-500 hover:text-slate-700'
          }`}
        >
          <Calendar size={16} /> Itinerary
        </button>
        <button
          onClick={() => setActiveTab('map')}
          className={`flex items-center gap-2 py-3 px-4 text-sm font-medium border-b-2 transition-colors ${
            activeTab === 'map' 
              ? 'border-brand-500 text-brand-600' 
              : 'border-transparent text-slate-500 hover:text-slate-700'
          }`}
        >
          <Map size={16} /> Map
        </button>
        <button
          onClick={() => setActiveTab('budget')}
          className={`flex items-center gap-2 py-3 px-4 text-sm font-medium border-b-2 transition-colors ${
            activeTab === 'budget' 
              ? 'border-brand-500 text-brand-600' 
              : 'border-transparent text-slate-500 hover:text-slate-700'
          }`}
        >
          <DollarSign size={16} /> Costs
        </button>
      </div>

      {/* Content Area */}
      <div className="flex-1 overflow-y-auto p-6 bg-slate-50/30">
        {activeTab === 'timeline' && <TripTimeline plan={plan} />}
        
        {activeTab === 'map' && (
          <div className="h-full flex flex-col items-center justify-center bg-slate-100 rounded-2xl border border-slate-200 border-dashed text-slate-400">
            <Map size={48} className="mb-2 opacity-50" />
            <p>Interactive Map View</p>
            <p className="text-xs">(Integration Ready)</p>
          </div>
        )}

        {activeTab === 'budget' && (
          <div className="h-full flex flex-col items-center justify-center bg-slate-100 rounded-2xl border border-slate-200 border-dashed text-slate-400">
            <DollarSign size={48} className="mb-2 opacity-50" />
            <p>Budget Breakdown Visualization</p>
            <p className="text-xs text-center max-w-xs mt-2">D3.js charts will go here to show spend per category (Hotel, Flight, Food).</p>
          </div>
        )}
      </div>
    </div>
  );
};
