"""Specialists without a live data source: the model answers from general knowledge.

Their output is labelled in code (not left to the prompt) so simulated data is
never presented as live.
"""

from collections.abc import Callable
from dataclasses import dataclass
from datetime import date

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage

from app.agents.common import SpecialistName, build_llm_input
from app.graph.state import TripState


@dataclass(frozen=True)
class SimulatedSpecialist:
    name: SpecialistName
    prompt: str
    # Prepended to the specialist's report and listed under "Data sources" in the final answer.
    source_note: str


FLIGHT_EXPERT = SimulatedSpecialist(
    name="FlightExpert",
    prompt="""You are the FlightExpert on a trip-planning team. Today's date is {today}.
You have no access to live flight search. From general knowledge, outline realistic flight \
options for the user's trip: likely airlines and routes (direct or with a connection), typical \
flight time and a typical economy price range. Present them as illustrative examples, never as \
bookable quotes, and never claim you checked availability. If the origin or dates are missing, \
state the assumption you made. Plain text with '-' bullets, under 150 words.""",
    source_note="Flights are illustrative examples generated by the model, not live data.",
)

HOTEL_SCOUT = SimulatedSpecialist(
    name="HotelScout",
    prompt="""You are the HotelScout on a trip-planning team. Today's date is {today}.
You have no access to live hotel availability or prices. From general knowledge, suggest 2-3 \
areas or well-known hotels that match the user's style and budget, with a typical nightly \
price range and why each fits. Present them as illustrative examples, never as confirmed \
availability. Plain text with '-' bullets, under 150 words.""",
    source_note=(
        "Hotels are illustrative examples generated by the model, not live availability or prices."
    ),
)

ACTIVITY_CURATOR = SimulatedSpecialist(
    name="ActivityCurator",
    prompt="""You are an Activity Curator on a trip-planning team. Today's date is {today}.
Suggest a mix of well-known highlights and lesser-known places at the destination, including a \
few places to eat, grouped by day if the trip length is known. If a WeatherAdvisor report is \
present, match the plan to it: outdoor activities on dry days, indoor ones on rainy or very \
hot days. Plain text with '-' bullets, under 200 words.""",
    source_note=(
        "Activities come from the model's general knowledge, not live listings; "
        "check opening hours and prices."
    ),
)

SIMULATED_SPECIALISTS = (FLIGHT_EXPERT, HOTEL_SCOUT, ACTIVITY_CURATOR)


def create_specialist_node(
    llm: BaseChatModel, spec: SimulatedSpecialist, today: Callable[[], date] = date.today
):
    async def specialist(state: TripState) -> dict:
        prompt = spec.prompt.format(today=today().isoformat())
        response = await llm.ainvoke(build_llm_input(prompt, state["messages"]))
        report = f"Note: {spec.source_note}\n\n{response.text}"
        return {
            "messages": [AIMessage(content=report, name=spec.name)],
            "sources": [spec.source_note],
        }

    return specialist


def get_specialists(llm: BaseChatModel, today: Callable[[], date] = date.today) -> dict:
    return {spec.name: create_specialist_node(llm, spec, today) for spec in SIMULATED_SPECIALISTS}
